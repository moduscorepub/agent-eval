/**
 * Jev question bank for judging one candidate change, and the states it is asked against.
 *
 * Three requests per candidate, each with only the context its questions need:
 * - change: the issue plus the diff (lockfiles stripped). Narrow yes/no questions, a few scores,
 *   and alternate phrasings of key questions to measure phrasing stability.
 * - reuse: the change's added source lines plus signatures of existing functions near it.
 * - files: each non-code, non-test file the change adds or modifies, one question per file.
 */
import * as fs from "node:fs";
import * as path from "node:path";
import type { Question } from "./jev";
import { type Task, baseDir, fileKind } from "./lib";
import { parseDefs } from "./conditions/shared";

const LOCKFILE = /(^|\/)(pnpm-lock\.yaml|bun\.lockb?|package-lock\.json|yarn\.lock|uv\.lock|Cargo\.lock|go\.sum)$/;
const PER_FILE_CAP = 6000;
const TOTAL_CAP = 60_000;

export interface DiffFile {
	path: string;
	status: "added" | "modified" | "deleted";
	kind: string;
	diff: string;
}

export function splitDiff(diff: string): DiffFile[] {
	return diff
		.split(/^(?=diff --git )/m)
		.filter(c => c.startsWith("diff --git "))
		.map(chunk => {
			const deleted = /^deleted file mode/m.test(chunk);
			const p = deleted ? chunk.match(/^diff --git a\/(\S+)/)![1]! : chunk.match(/^diff --git a\/\S+ b\/(\S+)/)![1]!;
			const body = chunk.slice(chunk.indexOf("\n@@") + 1 || chunk.length);
			return {
				path: p,
				status: /^new file mode/m.test(chunk) ? "added" : deleted ? "deleted" : "modified",
				kind: fileKind(p),
				diff: body.length > PER_FILE_CAP ? `${body.slice(0, PER_FILE_CAP)}\n... (truncated)` : body,
			} as DiffFile;
		})
		.filter(f => !LOCKFILE.test(f.path));
}

/** State for the whole-change questions. */
export function changeState(statement: string, files: DiffFile[]) {
	let budget = TOTAL_CAP;
	const diff = files.map(f => {
		const text = f.diff.length <= budget ? f.diff : `${f.diff.slice(0, Math.max(0, budget))}\n... (truncated)`;
		budget -= text.length;
		return { path: f.path, status: f.status, diff: text };
	});
	return { issue: statement, change: { files: files.map(f => `${f.status}: ${f.path}`), diff } };
}

/** State for the reuse question: added source lines, and existing functions near the change. */
export function reuseState(task: Pick<Task, "id">, files: DiffFile[]) {
	const src = files.filter(f => f.kind === "src" && f.status !== "deleted");
	const added = src
		.map(f => ({ path: f.path, added: f.diff.split("\n").filter(l => l.startsWith("+") && !l.startsWith("+++")).map(l => l.slice(1)).join("\n") }))
		.filter(f => f.added.trim());
	const root = baseDir(task.id);
	const dirs = [...new Set(src.map(f => path.dirname(f.path)))];
	const seen = new Set<string>();
	const existing: string[] = [];
	const ext = new Set(src.map(f => path.extname(f.path)));
	const candidates = [
		...src.map(f => f.path),
		...dirs.flatMap(d => (fs.existsSync(path.join(root, d)) ? fs.readdirSync(path.join(root, d)).map(n => path.join(d, n)) : [])),
	].filter(p => ext.has(path.extname(p)) && fileKind(p) === "src");
	for (const rel of candidates) {
		if (seen.has(rel) || existing.length >= 200) continue;
		seen.add(rel);
		const abs = path.join(root, rel);
		if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) continue;
		const lines = fs.readFileSync(abs, "utf8").split("\n");
		for (const d of parseDefs(rel, lines.join("\n"))) {
			if (d.kind !== "function" || d.name.startsWith("test")) continue;
			existing.push(`${rel}: ${(d.owner ? `${d.owner}.` : "") + lines[d.start - 1]!.trim().slice(0, 160)}`);
			if (existing.length >= 200) break;
		}
	}
	let budget = 24_000;
	const newCode = added.map(f => {
		const text = f.added.length <= budget ? f.added : `${f.added.slice(0, Math.max(0, budget))}\n... (truncated)`;
		budget -= text.length;
		return { path: f.path, code: text };
	});
	return { new_code: newCode, existing_functions: existing };
}

